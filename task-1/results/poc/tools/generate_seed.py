#!/usr/bin/env python3
"""Generate the POC seed data.

Produces:
  * ``initdb/02_seed.sql``           -- users / orders / payments
  * ``data/delivery_statuses.csv``   -- delivery statuses (CSV file storage)

The volume is scaled down compared to production (the task mentions ~1M rows
per run); the pipeline and the branching threshold are volume-agnostic.

Usage:  python tools/generate_seed.py
"""

from __future__ import annotations

import csv
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
POC_DIR = os.path.dirname(HERE)

N_USERS = 200
N_ORDERS = 900
DELIVERY_STATUSES = ["CREATED", "SHIPPED", "IN_TRANSIT", "DELIVERED", "RETURNED"]
SEGMENTS = ["RETAIL", "SMB", "ENTERPRISE"]

random.seed(42)


def main() -> None:
    os.makedirs(os.path.join(POC_DIR, "initdb"), exist_ok=True)
    os.makedirs(os.path.join(POC_DIR, "data"), exist_ok=True)

    users = []
    for uid in range(1, N_USERS + 1):
        users.append((uid, f"user{uid:03d}@example.com", f"Customer {uid:03d}", random.choice(SEGMENTS)))

    orders = []
    for oid in range(1, N_ORDERS + 1):
        user_id = random.randint(1, N_USERS)
        amount = round(random.uniform(100, 50000), 2)
        status = random.choice(["NEW", "PAID", "CANCELLED"])
        orders.append((oid, user_id, amount, status))

    payments = []
    pid = 0
    for oid, user_id, amount, status in orders:
        if status == "PAID":
            pid += 1
            payments.append((pid, oid, amount, "PAID"))
        elif random.random() < 0.15:
            pid += 1
            payments.append((pid, oid, round(amount * 0.5, 2), "PENDING"))

    seed_path = os.path.join(POC_DIR, "initdb", "02_seed.sql")
    with open(seed_path, "w", encoding="utf-8") as fh:
        fh.write("-- Auto-generated by tools/generate_seed.py -- do not edit manually.\n\n")
        fh.write("INSERT INTO users (id, email, full_name, segment) VALUES\n")
        fh.write(",\n".join(
            f"  ({u}, '{e}', '{n}', '{s}')" for u, e, n, s in users
        ) + ";\n\n")
        fh.write("INSERT INTO orders (id, user_id, amount, status) VALUES\n")
        fh.write(",\n".join(
            f"  ({o}, {u}, {a}, '{s}')" for o, u, a, s in orders
        ) + ";\n\n")
        fh.write("INSERT INTO payments (id, order_id, amount, status, paid_at) VALUES\n")
        fh.write(",\n".join(
            f"  ({p}, {o}, {a}, '{s}', now())" for p, o, a, s in payments
        ) + ";\n\n")
        fh.write("SELECT setval('users_id_seq', (SELECT max(id) FROM users));\n")
        fh.write("SELECT setval('orders_id_seq', (SELECT max(id) FROM orders));\n")
        fh.write("SELECT setval('payments_id_seq', (SELECT max(id) FROM payments));\n")

    csv_path = os.path.join(POC_DIR, "data", "delivery_statuses.csv")
    with open(csv_path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["order_id", "delivery_status", "updated_at"])
        for oid, user_id, amount, status in orders:
            writer.writerow([oid, random.choice(DELIVERY_STATUSES), "2024-01-01T00:00:00Z"])

    print(f"users={len(users)} orders={len(orders)} payments={len(payments)}")
    print(f"wrote {seed_path}")
    print(f"wrote {csv_path}")


if __name__ == "__main__":
    main()
